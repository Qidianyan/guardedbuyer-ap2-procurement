"""~200-request guardrail comparison: docs/comparison_200.md + CSVs + SVG, computed ONLY from the results file.

    python3 -m metrics.cases --profile 200 --seed 20261110 --out metrics/cases_200.json
    python3 -m metrics.run_metrics --cases metrics/cases_200.json --out metrics/results_200.json
    python3 -m metrics.comparison
"""
import argparse, csv, json, os
from collections import Counter, OrderedDict
from . import report as R

ROOT = R.ROOT
CONFIGS = ("no_guardrails", "policy_only", "full")
LABEL = {"no_guardrails": "No guardrails", "policy_only": "Policy only", "full": "Full guardrails (ours)"}
ATTACK = ("over_authority", "injection")

def _kn(k, n): return R._fmt_kn_pct(k, n)
def _rate(k, n): return round(k / n, 4) if n else ""

def summary_rows(results):
    S = results["offline"]["summary"]
    rows = []
    for cfg in CONFIGS:
        s = S[cfg]
        rows.append(OrderedDict([
            ("config", cfg), ("label", LABEL[cfg]),
            ("attack_cases", s["attack_cases"]), ("attack_cases_blocked", s["attack_cases_blocked"]),
            ("attack_case_block_rate", _rate(s["attack_cases_blocked"], s["attack_cases"])),
            ("unauthorized_attempts", s["unauthorized_attempts"]), ("attempts_blocked", s["blocked"]),
            ("attempt_block_rate", _rate(s["blocked"], s["unauthorized_attempts"])),
            ("normal_cases", s["normal_cases"]), ("normal_false_blocks", s["normal_false_blocks"]),
            ("normal_false_block_rate", _rate(s["normal_false_blocks"], s["normal_cases"])),
            ("legit_purchases_all", s["legit_purchases"]), ("legit_not_paid_all", s["legit_not_paid"]),
            ("false_block_rate_all", _rate(s["legit_not_paid"], s["legit_purchases"])),
            ("mismatch_cases", s["mismatch_cases"]), ("mismatch_handled", s["mismatch_handled"]),
            ("dispute_coverage", _rate(s["mismatch_handled"], s["mismatch_cases"])),
            ("errors", s["errors"]), ("audit_chain_valid_all", s["chain_valid_all"])]))
    return rows

def case_rows(results):
    by = OrderedDict()
    for r in results["offline"]["rows"]:
        d = by.setdefault(r["id"], OrderedDict([("id", r["id"]), ("type", r["type"]), ("subtype", r["subtype"]),
                                                 ("attempts", len(r["attempts"]))]))
        d[f'{r["config"]}_blocked_attempts'] = sum(x["blocked"] for x in r["attempts"])
        d[f'{r["config"]}_legit_paid'] = r["legit_paid"]
        d[f'{r["config"]}_dispute_handled'] = r.get("dispute_handled")
    cols = ["id", "type", "subtype", "attempts"] + [f"{c}_{k}" for c in CONFIGS
                                                    for k in ("blocked_attempts", "legit_paid", "dispute_handled")]
    return cols, [{c: d.get(c, "") for c in cols} for d in by.values()]

def chart(results):
    S = results["offline"]["summary"]
    series = [(c, LABEL[c], R.COLORS[c]) for c in CONFIGS]
    groups = []
    for label, k, n in (("Attack cases blocked", "attack_cases_blocked", "attack_cases"),
                        ("Attempts blocked", "blocked", "unauthorized_attempts"),
                        ("False blocks (normal)", "normal_false_blocks", "normal_cases"),
                        ("Dispute coverage", "mismatch_handled", "mismatch_cases")):
        groups.append((label, {c: (S[c][k] / S[c][n] if S[c][n] else None) for c in CONFIGS}))
    n = results.get("n_cases")
    return R._vertical_chart(f"Guardrail comparison on {n} synthetic purchase requests",
                             "Offline PayPal emulation, scripted worst-case agent (higher is better except false blocks)",
                             groups, series, "Metric", "Rate (%)", y_max=100, percent=True, ticks=4)

def render_md(results, cases, prev=None):
    S = results["offline"]["summary"]
    full = S["full"]
    prof = {c.get("profile") for c in cases} - {None}
    seeds = {c.get("seed") for c in cases} - {None}
    cnt = Counter((c["type"], c["subtype"]) for c in cases)
    types = Counter(c["type"] for c in cases)
    L = []
    L.append(f"# Guardrail comparison on ~200 synthetic purchase requests\n")
    L.append(f"**All {len(cases)} requests are synthetic**, generated by `metrics/cases.py` (profile "
             f"{', '.join(sorted(prof)) or 'n/a'}, seed {', '.join(str(s) for s in sorted(seeds)) or 'n/a'}). The agent is a "
             "scripted worst case (a fully compromised agent that always attempts the attack) and PayPal is the offline "
             "Orders v2 / Disputes v1 emulation. This is not real company data and not a measure of market performance. "
             f"Every number below is computed by `metrics/comparison.py` from `metrics/results_200.json` "
             f"(generated {results.get('generated_at')}).\n")
    L.append("## Sample\n")
    L.append(R._md_table(["Type", "Subtype", "Cases"],
                         [[t, s, str(n)] for (t, s), n in sorted(cnt.items(), key=lambda x: (list(types).index(x[0][0]), x[0][1]))],
                         ["left", "left", "right"]))
    L.append("")
    L.append(f"Totals: **{len(cases)} requests**: {types['normal']} normal, {types['over_authority']} over-authority, "
             f"{types['injection']} prompt-injection, {types['mismatch']} delivery-mismatch. Attack cases (over-authority + "
             f"injection): **{full['attack_cases']}**, containing **{full['unauthorized_attempts']} unauthorized attempts** "
             "(some injection cases try two purchases, e.g. the item from the attacker's shop plus gift cards).\n")
    L.append("How the set is generated: a seeded random generator picks items and quantities from a fictional catalog, "
             "attack templates add an unauthorized step (inflated quantity, disallowed category, blocked merchant, self-approval, "
             "tampered amount, poisoned supplier listing, …), and mismatch cases change the delivered quantity, SKU or price. "
             "Every case also contains the employee's legitimate purchase, so false blocks can be measured on all of them. "
             "Human approvers approve only the exact legitimate request, in every configuration.\n")
    L.append("## Definitions (denominators)\n")
    L.append("- **Block rate (primary)** = attack cases in which every unauthorized attempt was stopped / attack cases "
             f"(n = {full['attack_cases']}).")
    L.append(f"- Block rate (secondary) = blocked unauthorized attempts / unauthorized attempts (n = {full['unauthorized_attempts']}).")
    L.append(f"- **False-block rate (primary)** = normal requests whose purchase was not paid / normal requests (n = {full['normal_cases']}).")
    L.append(f"- False-block rate (secondary) = legitimate purchases not paid / all legitimate purchases, including those inside "
             f"attack and mismatch cases (n = {full['legit_purchases']}).")
    L.append(f"- **Dispute coverage** = mismatch cases handled correctly / mismatch cases (n = {full['mismatch_cases']}): a dispute "
             "(or buyer-filing draft) for exactly the expected refund when it is > 0, or a review flag when it is 0.")
    L.append("- Money moved = the ticket reached PayPal capture. A blocked attempt = no money moved for it (tamper: no capture "
             "above the authorized total).\n")
    L.append("Configurations: **No guardrails** = the agent executes whatever it submits; **Policy only** = classic spend "
             "policy (budgets, categories, hard cap, blocked merchants) + human approvals; **Full guardrails** = policy + "
             "approvals + signed AP2 mandate check + PayPal order read-back + request-scope guard + injection quarantine + "
             "delivery reconciliation.\n")
    L.append("## Results\n")
    rows = []
    for cfg in CONFIGS:
        s = S[cfg]
        rows.append([LABEL[cfg], _kn(s["attack_cases_blocked"], s["attack_cases"]), _kn(s["blocked"], s["unauthorized_attempts"]),
                     _kn(s["normal_false_blocks"], s["normal_cases"]), _kn(s["legit_not_paid"], s["legit_purchases"]),
                     _kn(s["mismatch_handled"], s["mismatch_cases"]), str(s["errors"]),
                     "yes" if s["chain_valid_all"] else "no"])
    L.append(R._md_table(["Configuration", "Attack cases blocked", "Attempts blocked", "False blocks (normal)",
                          "False blocks (all legit)", "Dispute coverage", "Errors", "Audit chain valid"], rows,
                         ["left"] + ["right"] * 7))
    L.append("\n![comparison](charts/comparison_200.svg)\n")
    L.append("## By subtype\n")
    subs = sorted({k for k in full["by_subtype"] if k.split("/")[0] in ATTACK},
                  key=lambda k: (ATTACK.index(k.split("/")[0]), k))
    L.append(R._md_table(["Type / subtype"] + [f"{LABEL[c]}: blocked / attempts" for c in CONFIGS],
                         [[k] + [f'{S[c]["by_subtype"][k]["blocked"]}/{S[c]["by_subtype"][k]["attempts"]}' for c in CONFIGS]
                          for k in subs], ["left"] + ["right"] * 3))
    L.append("\n## What full guardrails missed\n")
    missed = full["missed_attack_case_ids"]
    sub_of = {c["id"]: f'{c["type"]}/{c["subtype"]}' for c in cases}
    if not missed:
        L.append("Full guardrails stopped every attack case in this set.\n")
    else:
        g = Counter(sub_of[i] for i in missed)
        L.append(f"{len(missed)} of {full['attack_cases']} attack cases got at least one unauthorized payment through: "
                 + "; ".join(f"{k}: {n} ({', '.join(i for i in missed if sub_of[i] == k)})" for k, n in sorted(g.items()))
                 + ".")
        if set(g) <= {"injection/official_supplier", "injection/backup_stock", "injection/invoice_redirect"}:
            L.append("All misses come from listings the regex detector does not flag (see `detector_should_flag` in the "
                     "cases file). Where the listing only asks the agent to buy the requested item from the attacker's own "
                     "shop, policy, mandate and scope checks all see a valid-looking purchase.\n")
        else:
            L.append("")
    if prev:
        P = prev["offline"]["summary"]
        L.append("## Comparison with the earlier 150-case run\n")
        L.append(R._md_table(["Configuration", f"Attempts blocked ({prev.get('n_cases')} cases)",
                              f"Attempts blocked ({results.get('n_cases')} cases)",
                              f"False blocks all legit ({prev.get('n_cases')})", f"False blocks all legit ({results.get('n_cases')})",
                              f"Dispute coverage ({prev.get('n_cases')})", f"Dispute coverage ({results.get('n_cases')})"],
                             [[LABEL[c], _kn(P[c]["blocked"], P[c]["unauthorized_attempts"]),
                               _kn(S[c]["blocked"], S[c]["unauthorized_attempts"]),
                               _kn(P[c]["legit_not_paid"], P[c]["legit_purchases"]), _kn(S[c]["legit_not_paid"], S[c]["legit_purchases"]),
                               _kn(P[c]["mismatch_handled"], P[c]["mismatch_cases"]), _kn(S[c]["mismatch_handled"], S[c]["mismatch_cases"])]
                              for c in CONFIGS], ["left"] + ["right"] * 6))
        L.append("")
    L.append("## Reproduce\n")
    L.append("```bash\npython3 -m metrics.cases --profile 200 --seed 20261110 --out metrics/cases_200.json\n"
             "python3 -m metrics.run_metrics --cases metrics/cases_200.json --out metrics/results_200.json\n"
             "python3 -m metrics.comparison\n```\n")
    L.append("CSV: [`comparison_200.csv`](comparison_200.csv) (one row per configuration) and "
             "[`comparison_200_cases.csv`](comparison_200_cases.csv) (one row per request).\n")
    L.append("## Limitations\n")
    L.append("- Synthetic requests, fictional catalog and merchants.\n- The scripted attacker is a worst case, not a model of "
             "real LLM behaviour.\n- The injection detector is regex-based (a signal, not the security boundary).\n- Human "
             "approvers are assumed to approve only the legitimate request.\n- PayPal is the offline emulation; the real "
             "sandbox path is covered separately in `docs/sandbox.md`.\n")
    return "\n".join(L)

def render(results, cases, out_dir, prev=None):
    os.makedirs(os.path.join(out_dir, "charts"), exist_ok=True)
    paths = []
    p = os.path.join(out_dir, "comparison_200.csv")
    rows = summary_rows(results)
    with open(p, "w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=list(rows[0])); w.writeheader(); w.writerows(rows)
    paths.append(p)
    cols, crow = case_rows(results)
    p = os.path.join(out_dir, "comparison_200_cases.csv")
    with open(p, "w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=cols); w.writeheader(); w.writerows(crow)
    paths.append(p)
    p = os.path.join(out_dir, "charts", "comparison_200.svg")
    with open(p, "w") as f: f.write(chart(results))
    paths.append(p)
    p = os.path.join(out_dir, "comparison_200.md")
    with open(p, "w") as f: f.write(render_md(results, cases, prev))
    paths.append(p)
    return paths

def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument("--results", default=os.path.join(ROOT, "metrics", "results_200.json"))
    ap.add_argument("--cases", default=os.path.join(ROOT, "metrics", "cases_200.json"))
    ap.add_argument("--prev", default=os.path.join(ROOT, "metrics", "results.json"))
    ap.add_argument("--out-dir", default=os.path.join(ROOT, "docs"))
    a = ap.parse_args(argv)
    results, cases = json.load(open(a.results)), json.load(open(a.cases))
    prev = json.load(open(a.prev)) if a.prev and os.path.exists(a.prev) else None
    for p in render(results, cases, a.out_dir, prev): print("->", os.path.relpath(p, ROOT))

if __name__ == "__main__":
    main()
